-- Generated schema.json is this inventory of the embedded application baseline.
-- Exclude data-dependent counters and database names, retain behavioral metadata.
SELECT CAST(JSON_ARRAY('column',TABLE_NAME,COLUMN_NAME,ORDINAL_POSITION,COLUMN_TYPE,
    IS_NULLABLE,COLUMN_DEFAULT,EXTRA,GENERATION_EXPRESSION,COLLATION_NAME) AS CHAR) AS definition
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
UNION ALL
SELECT CAST(JSON_ARRAY('index',TABLE_NAME,INDEX_NAME,SEQ_IN_INDEX,COLUMN_NAME,
    NON_UNIQUE,SUB_PART,INDEX_TYPE,IS_VISIBLE,EXPRESSION) AS CHAR)
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE()
UNION ALL
SELECT CAST(JSON_ARRAY('check',t.TABLE_NAME,c.CONSTRAINT_NAME,c.CHECK_CLAUSE,t.ENFORCED) AS CHAR)
FROM information_schema.CHECK_CONSTRAINTS c
JOIN information_schema.TABLE_CONSTRAINTS t
    ON c.CONSTRAINT_SCHEMA=t.CONSTRAINT_SCHEMA AND c.CONSTRAINT_NAME=t.CONSTRAINT_NAME
WHERE c.CONSTRAINT_SCHEMA=DATABASE()
ORDER BY definition
