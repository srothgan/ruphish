CREATE TABLE ruphish_mailboxes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  owner_id BIGINT NOT NULL,
  name VARCHAR(255) COLLATE "C" NOT NULL,
  revision BIGINT NOT NULL DEFAULT 1,
  enabled BOOLEAN NOT NULL,
  host VARCHAR(255) COLLATE "C" NOT NULL,
  port BIGINT NOT NULL,
  username VARCHAR(255) COLLATE "C" NOT NULL,
  password TEXT COLLATE "C" NOT NULL,
  tls BOOLEAN NOT NULL,
  folder VARCHAR(255) COLLATE "C" NOT NULL,
  restrict_domain VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  delete_reported BOOLEAN NOT NULL DEFAULT FALSE,
  frequency BIGINT NOT NULL DEFAULT 60,
  uidvalidity BIGINT NOT NULL DEFAULT 0,
  last_uid BIGINT NOT NULL DEFAULT 0,
  initialized BOOLEAN NOT NULL DEFAULT FALSE,
  next_check BIGINT NOT NULL DEFAULT 0,
  lease BIGINT NOT NULL DEFAULT 0,
  last_check BIGINT NOT NULL DEFAULT 0,
  last_success BIGINT NOT NULL DEFAULT 0,
  modified_date VARCHAR(40) COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"')),
  last_login VARCHAR(40) COLLATE "C" NOT NULL DEFAULT '0001-01-01T00:00:00Z',
  failures BIGINT NOT NULL DEFAULT 0,
  code VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  ignore_cert_errors BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (id),
  CONSTRAINT mailbox_name UNIQUE (owner_id,name),
  CHECK (port BETWEEN 1 AND 65535)
);

