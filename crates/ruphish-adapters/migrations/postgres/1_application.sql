  PRIMARY KEY (webhook_id)
);

CREATE TABLE ruphish_webhook_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  webhook_id BIGINT NOT NULL,
  revision BIGINT NOT NULL,
  event_id BIGINT NOT NULL,
  state VARCHAR(255) COLLATE "C" NOT NULL DEFAULT 'queued',
  attempt BIGINT NOT NULL DEFAULT 0,
  due BIGINT NOT NULL DEFAULT 0,
  lease BIGINT NOT NULL DEFAULT 0,
  code VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  PRIMARY KEY (id),
  CONSTRAINT webhook_event UNIQUE (webhook_id,event_id)
);

CREATE TABLE ruphish_webhook_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  job_id BIGINT NOT NULL,
  attempt BIGINT NOT NULL,
  started BIGINT NOT NULL,
