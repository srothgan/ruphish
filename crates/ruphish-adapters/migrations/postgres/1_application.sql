CREATE TABLE ruphish_sessions (
  id VARCHAR(255) COLLATE "C" NOT NULL,
  data TEXT COLLATE "C" NOT NULL,
  expires BIGINT NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE ruphish_secrets (
  name VARCHAR(255) COLLATE "C" NOT NULL,
  value BYTEA NOT NULL,
  PRIMARY KEY (name)
);

CREATE TABLE ruphish_campaign_groups (
  campaign_id BIGINT NOT NULL,
  ordinal BIGINT NOT NULL,
  group_id BIGINT NOT NULL,
  PRIMARY KEY (campaign_id,ordinal)
);

CREATE TABLE ruphish_campaign_policy (
  campaign_id BIGINT NOT NULL,
  capture_credentials BOOLEAN NOT NULL,
  capture_passwords BOOLEAN NOT NULL,
  redirect_url TEXT COLLATE "C" NOT NULL,
  PRIMARY KEY (campaign_id)
);

CREATE TABLE ruphish_campaign_launch (
  owner_id BIGINT NOT NULL,
  key VARCHAR(255) COLLATE "C" NOT NULL,
  fingerprint VARCHAR(255) COLLATE "C" NOT NULL,
  campaign_id BIGINT NOT NULL,
  PRIMARY KEY (owner_id,key)
);

CREATE TABLE ruphish_delivery (
  result_id BIGINT NOT NULL,
  campaign_id BIGINT NOT NULL,
  state VARCHAR(255) COLLATE "C" NOT NULL,
  due BIGINT NOT NULL,
  retries BIGINT NOT NULL DEFAULT 0,
  generation BIGINT NOT NULL DEFAULT 0,
  lease_until BIGINT NOT NULL DEFAULT 0,
  last_claim BIGINT NOT NULL DEFAULT 0,
  code VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  smtp_code BIGINT,
  stage VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  profile_revision VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  PRIMARY KEY (result_id),
  CHECK (state IN ('ready','preparing','submitting','retry','accepted','failed','unknown','blocked','cancelled')),
  CHECK (retries BETWEEN 0 AND 8)
);

CREATE TABLE ruphish_delivery_attempt (
  result_id BIGINT NOT NULL,
  generation BIGINT NOT NULL,
  started BIGINT NOT NULL,
  finished BIGINT,
  state VARCHAR(255) COLLATE "C" NOT NULL,
  stage VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  smtp_code BIGINT,
  message_id VARCHAR(255) COLLATE "C" NOT NULL,
  resource_revision VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  PRIMARY KEY (result_id,generation)
);

CREATE TABLE ruphish_profile_cooldown (
  profile_id BIGINT NOT NULL,
  until_time BIGINT NOT NULL,
  revision VARCHAR(255) COLLATE "C" NOT NULL,
  blocked BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (profile_id)
);

CREATE TABLE ruphish_legacy_queue_issues (
  mail_log_id BIGINT NOT NULL,
