  PRIMARY KEY (mail_log_id)
);

CREATE TABLE ruphish_domains (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  owner_id BIGINT NOT NULL,
  name VARCHAR(255) COLLATE "C" NOT NULL,
  origin VARCHAR(512) COLLATE "C" NOT NULL,
  hostname VARCHAR(255) COLLATE "C" NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  revision BIGINT NOT NULL DEFAULT 1,
  challenge VARCHAR(255) COLLATE "C" NOT NULL,
  challenge_expires BIGINT NOT NULL,
  checked_at BIGINT NOT NULL DEFAULT 0,
  verified_until BIGINT NOT NULL DEFAULT 0,
  control BOOLEAN NOT NULL DEFAULT FALSE,
  dns BOOLEAN NOT NULL DEFAULT FALSE,
  routing BOOLEAN NOT NULL DEFAULT FALSE,
  tls BOOLEAN NOT NULL DEFAULT FALSE,
  code VARCHAR(255) COLLATE "C" NOT NULL DEFAULT 'domain_not_verified',
  due BIGINT NOT NULL DEFAULT 0,
  lease_until BIGINT NOT NULL DEFAULT 0,
  generation BIGINT NOT NULL DEFAULT 0,
  failures BIGINT NOT NULL DEFAULT 0,
  routing_proof VARCHAR(255) COLLATE "C" NOT NULL DEFAULT '',
  PRIMARY KEY (id),
  CONSTRAINT domain_origin UNIQUE (owner_id,origin)
);

CREATE TABLE ruphish_domain_claims (
  hostname VARCHAR(255) COLLATE "C" NOT NULL,
  owner_id BIGINT NOT NULL,
  PRIMARY KEY (hostname)
);

CREATE TABLE ruphish_campaign_domains (
  campaign_id BIGINT NOT NULL,
