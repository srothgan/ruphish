-- PostgreSQL application baseline. UTC wire timestamps retain nanosecond revisions.
-- Tables use exact comparisons; search queries choose their own semantics.
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  username VARCHAR(255) COLLATE "C" NOT NULL,
  hash VARCHAR(255) COLLATE "C",
  api_key VARCHAR(255) COLLATE "C" NOT NULL,
  role_id BIGINT,
  password_change_required BOOLEAN,
  last_login VARCHAR(40) COLLATE "C",
  account_locked BOOLEAN,
  PRIMARY KEY (id)
);

CREATE TABLE templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT,
  name VARCHAR(255) COLLATE "C",
  subject VARCHAR(255) COLLATE "C",
  text TEXT COLLATE "C",
  html TEXT COLLATE "C",
  modified_date VARCHAR(40) COLLATE "C",
  envelope_sender VARCHAR(255) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE targets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  first_name VARCHAR(255) COLLATE "C",
  last_name VARCHAR(255) COLLATE "C",
  email VARCHAR(255) COLLATE "C",
  position VARCHAR(255) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  campaign_id BIGINT,
  user_id BIGINT,
  r_id VARCHAR(255) COLLATE "C",
  email VARCHAR(255) COLLATE "C",
  first_name VARCHAR(255) COLLATE "C",
  last_name VARCHAR(255) COLLATE "C",
  status VARCHAR(255) COLLATE "C" NOT NULL,
  ip VARCHAR(255) COLLATE "C",
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  position VARCHAR(255) COLLATE "C",
  send_date VARCHAR(40) COLLATE "C",
  reported BOOLEAN DEFAULT FALSE,
  modified_date VARCHAR(40) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE pages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT,
  name VARCHAR(255) COLLATE "C",
  html TEXT COLLATE "C",
  modified_date VARCHAR(40) COLLATE "C",
  capture_credentials BOOLEAN,
  capture_passwords BOOLEAN,
  redirect_url TEXT COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT,
  name VARCHAR(255) COLLATE "C",
  modified_date VARCHAR(40) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE group_targets (
  group_id BIGINT,
  target_id BIGINT
);

CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  campaign_id BIGINT,
  email VARCHAR(255) COLLATE "C",
  time VARCHAR(40) COLLATE "C",
  message VARCHAR(255) COLLATE "C",
  details TEXT COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT,
  name VARCHAR(255) COLLATE "C" NOT NULL,
  created_date VARCHAR(40) COLLATE "C",
  completed_date VARCHAR(40) COLLATE "C",
  template_id BIGINT,
  page_id BIGINT,
  status VARCHAR(255) COLLATE "C",
  url TEXT COLLATE "C",
  smtp_id BIGINT,
  launch_date VARCHAR(40) COLLATE "C",
  send_by_date VARCHAR(40) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  template_id BIGINT,
  content TEXT COLLATE "C",
  type VARCHAR(255) COLLATE "C",
  name VARCHAR(255) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE smtp (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT,
  interface_type VARCHAR(255) COLLATE "C",
  name VARCHAR(255) COLLATE "C",
  host VARCHAR(255) COLLATE "C",
  username VARCHAR(255) COLLATE "C",
  password TEXT COLLATE "C",
  from_address VARCHAR(255) COLLATE "C",
  modified_date VARCHAR(40) COLLATE "C" DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"')),
  ignore_cert_errors BOOLEAN,
  PRIMARY KEY (id)
);

CREATE TABLE headers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  key VARCHAR(255) COLLATE "C",
  value TEXT COLLATE "C",
  smtp_id BIGINT,
  PRIMARY KEY (id)
);

CREATE TABLE mail_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  campaign_id BIGINT,
  user_id BIGINT,
  send_date VARCHAR(40) COLLATE "C",
  send_attempt BIGINT,
  r_id VARCHAR(255) COLLATE "C",
  processing BOOLEAN,
  PRIMARY KEY (id)
);

CREATE TABLE email_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT,
  template_id BIGINT,
  page_id BIGINT,
  first_name VARCHAR(255) COLLATE "C",
  last_name VARCHAR(255) COLLATE "C",
  email VARCHAR(255) COLLATE "C",
  position VARCHAR(255) COLLATE "C",
  url TEXT COLLATE "C",
  r_id VARCHAR(255) COLLATE "C",
  from_address VARCHAR(255) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  slug VARCHAR(255) COLLATE "C" NOT NULL,
  name VARCHAR(255) COLLATE "C" NOT NULL,
  description VARCHAR(255) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  slug VARCHAR(255) COLLATE "C" NOT NULL,
  name VARCHAR(255) COLLATE "C" NOT NULL,
  description VARCHAR(255) COLLATE "C",
  PRIMARY KEY (id)
);

CREATE TABLE role_permissions (
  role_id BIGINT NOT NULL,
  permission_id BIGINT NOT NULL
);

CREATE TABLE webhooks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  name VARCHAR(255) COLLATE "C",
  url TEXT COLLATE "C",
  secret TEXT COLLATE "C",
  is_active BOOLEAN DEFAULT FALSE,
  PRIMARY KEY (id)
);

